// Builds plan/PROJECT-PLAN.md from tickets.json and the module notes. Run after build-json.mjs.
import fs from 'node:fs';
import { notes } from './seed/tech-notes.mjs';
const { rows } = JSON.parse(fs.readFileSync('tickets.json', 'utf8'));
const epics = rows.filter(r => r.type === 'epic'), tasks = rows.filter(r => r.type === 'task');
const byId = Object.fromEntries(rows.map(r => [r.id, r]));
const sum = (a, f) => a.reduce((x, r) => x + f(r), 0);
const sprints = [...new Set(tasks.map(t => t.sprint))].sort((a, b) => +a.slice(1) - +b.slice(1));
const total = sum(tasks, t => t.hours);
const cap = (s) => s;

let md = `# Orty — Grocery Store Management System: project plan

_Generated by \`tools/plan-doc.mjs\` from the tickets. Do not edit by hand; change tickets and regenerate._

## 1. Scope

A web POS for a grocery store covering 23 features: products, multiple barcodes, billing, bill history, price checker, barcode printing, stock, purchase suggestions and orders, receiving, low-stock, web/mobile access, offline mode, returns, expiry and batches, customer credit, cash closing, reports, backup, offline conflict handling, audit log, price history and multiple branches. Settings, payment methods and receipts were added as module SET.

**Stack:** .NET 8 API (Controllers → Services → Repositories, DTOs only), Angular 19+ standalone UI, **SQL Server 2008 R2**. Additive, idempotent migrations; no OFFSET/FETCH, CONCAT, IIF, THROW or SEQUENCE.

**Size:** ${epics.length} modules, ${rows.filter(r => r.type === 'story').length} stories, ${tasks.length} tasks, ${total} estimated hours.

## 2. Sprint plan (2-week sprints from 2026-11-30)

| Sprint | Dates | Modules | Tasks | Hours |
|--------|-------|---------|-------|-------|
`;
for (const s of sprints) {
  const ts = tasks.filter(t => t.sprint === s);
  const mods = [...new Set(ts.map(t => t.module_name))];
  md += `| ${s} | ${ts[0].start} to ${ts.map(t => t.due).sort().pop()} | ${mods.join(', ')} | ${ts.length} | ${sum(ts, t => t.hours)} |\n`;
}
md += `
Hours are effort estimates, not calendar time. A sprint holds as much work as the team can deliver in two weeks; if the team has fewer hours per sprint than the table shows, the plan stretches proportionally. Confirm team size and weekly capacity to turn this into a delivery date.

## 3. Modules

| Ticket | Module | Priority | Sprint | Hours | Depends on |
|--------|--------|----------|--------|-------|------------|
`;
for (const e of epics) md += `| [${e.id}](../tickets/${e.id}.md) | ${e.title} | ${e.priority} | ${e.sprint} | ${e.hours} | ${e.depends_on.split(' ').filter(Boolean).map(d => byId[d]?.module).join(', ') || '-'} |\n`;

md += `
## 4. Roles

| Role | Can do |
|------|--------|
| Admin / Owner | Everything: all branches, reports, prices, users, backup, audit log, settings |
| Manager | Products, stock, suggestions, orders, bill history, returns approval, cash closing, credit, sync review |
| Cashier | Billing, price checker, holding bills, returns within allowed limits |

## 5. Definition of done (every ticket)

- Code follows Controllers → Services → Repositories with DTOs; async with CancellationToken.
- SQL compatible with SQL Server 2008 R2; generated EF SQL checked for prohibited syntax.
- API tests: functional, negative, boundary and permission cases; QA scope is the API layer only.
- Ticket Markdown updated (subtasks ticked), \`tickets.json\` rebuilt, dashboard shows it.

## 6. QA approach (API layer only)

Per module: functional, negative, boundary, security (authN/authZ, injection, mass assignment, cross-branch access) and a performance smoke test. Module QA tickets sit with each module; module QAA covers the cross-cutting suite, SQL 2008 R2 audit and load smoke.

## 7. Risks

| Risk | Impact | Mitigation |
|------|--------|------------|
| No SQL Server 2008 R2 test instance | Migrations and queries unverified against the real target | Obtain a staging instance; run migrations and the integration suite on it before sprint 2 ends |
| Template code uses OFFSET/FETCH paging | Breaks on 2008 R2 | Ticket T-0277; shared TOP-based paging helper already in place |
| Offline sync and stock conflicts | Wrong stock, lost sales | Idempotent sync, never block a sale, review queue (modules OFF, SYN) |
| Branch scoping added late | Rework of every query | BranchId on scoped tables from the first schema (module FND) |
| Scope size | Schedule slip | Priorities P0 to P2; P2 modules can slip without blocking billing |

## 8. Open questions (from the module notes)

`;
for (const e of epics) { const o = notes[e.module]; if (o && o.open.length) md += `**${e.title}**\n${o.open.map(q => `- ${q}`).join('\n')}\n\n`; }
md += `## 9. How progress is tracked

Tickets are Markdown files in \`tickets/\`. A GitHub Action rebuilds \`tickets.json\` on every push. The Orty "Project progress" screen and the shared dashboard read that file.
`;
fs.mkdirSync('plan', { recursive: true });
fs.writeFileSync('plan/PROJECT-PLAN.md', md);
console.log('plan/PROJECT-PLAN.md written');
